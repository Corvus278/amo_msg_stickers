import type { SendItem } from '../db.types';
import type { OpenedBy } from '../hoverPopup.types';

export type PickerCallbacks = {
  /**
   * Колбэк на выбор стикера или GIF: отправляет его в открытый чат. Отклонённый промис —
   * отправка не удалась, текст ошибки показывается в статусе пикера.
   */
  onSend: (item: SendItem) => Promise<void>;

  /**
   * Колбэк на закрытие пикера: вызывается один раз на каждое закрытие открытого
   * пикера — снаружи через `close()` и изнутри (Escape, успешная отправка).
   */
  onClose: () => void;

  /**
   * Колбэк на снятие последней причины удержания: фокус ушёл из поля, закрыт диалог файла,
   * закончились импорт или конвертация.
   */
  onHoldRelease: () => void;
};

export type PickerHandle = {
  /**
   * Хост пикера с shadow root. Вставляется в DOM вызывающей стороной: `position: fixed`
   * панели считается от ближайшего предка с transform.
   */
  element: HTMLElement;

  /**
   * Открыт ли пикер сейчас.
   */
  readonly isOpen: boolean;

  /**
   * Уходит ли закрытый пикер анимацией закрытия: панель ещё видна, но уже не открыта.
   */
  readonly isClosing: boolean;

  /**
   * Удерживает ли что-то пикер открытым: фокус в его текстовом поле, открытый диалог
   * выбора файла, идущий импорт или конвертация. Уход курсора удержанный пикер не
   * закрывает, `close()` закрывает всегда.
   */
  isHeld: () => boolean;

  /**
   * Открывает пикер; уже открытый не трогает.
   *
   * @param openedBy — чем открыт: наведение не уводит фокус из поля сообщения
   */
  open: (openedBy: OpenedBy) => void;

  /**
   * Закрывает пикер и вызывает `onClose`; закрытый не трогает. Панель ещё уходит
   * анимацией, но `isOpen` уже `false`.
   */
  close: () => void;

  /**
   * Переключает тему пикера вслед за темой страницы.
   */
  setTheme: (isDark: boolean) => void;
};
