import type { Settings } from '../../../../host.types';

export type SettingsDraft = {
  /**
   * Значения полей формы, ещё не сохранённые.
   */
  draft: Settings;

  /**
   * Меняет значение одного поля формы.
   */
  changeField: (key: keyof Settings, value: string) => void;

  /**
   * Сохраняет форму в хранилище окружения без пробелов по краям и показывает статус
   * «Сохранено»; новые ключи сразу доступны остальным вкладкам пикера. Промис не
   * отклоняется: ошибка уходит в статус.
   */
  save: () => Promise<void>;
};

export type SettingsEdits = {
  /**
   * Настройки, поверх которых сделаны правки: после их перечитывания правки не
   * применяются.
   */
  base: Settings;

  /**
   * Изменённые поля формы; остальные берутся из настроек.
   */
  values: Partial<Settings>;
};
