/**
 * Раздел ленты стикеров на входе раскладки.
 */
export type StickerSection<T> = {
  /**
   * Идентификатор раздела: `pack.id` пака (`custom`, `tg:<имя>`), `'recent'` — недавние стикеры.
   */
  id: string;

  /**
   * Стикеры раздела в порядке показа. Пустой список — раздел с подсказкой вместо сетки.
   */
  items: T[];
};

/**
 * Вид ряда ленты: заголовок раздела или ряд ячеек.
 */
export type StickerRowKind = 'header' | 'cells';

/**
 * Ряд ленты стикеров с готовой геометрией.
 */
export type StickerRow<T> = {
  /**
   * Заголовок раздела или ряд ячеек.
   */
  kind: StickerRowKind;

  /**
   * Раздел, которому принадлежит ряд.
   */
  sectionId: string;

  /**
   * Верх ряда от начала ленты, в пикселях.
   */
  top: number;

  /**
   * Высота ряда в пикселях: у заголовка — `HEADER_HEIGHT`, у ряда ячеек — сторона ячейки.
   */
  height: number;

  /**
   * Стикеры ряда слева направо, не больше `COLUMNS`. Пусто у заголовка и у ряда подсказки пустого раздела.
   */
  items: T[];
};

/**
 * Верх раздела — верх его заголовка.
 */
export type SectionTop = {
  /**
   * Идентификатор раздела.
   */
  sectionId: string;

  /**
   * Верх заголовка раздела от начала ленты, в пикселях.
   */
  top: number;
};

/**
 * Раскладка ленты стикеров.
 */
export type StickerLayout<T> = {
  /**
   * Ряды сверху вниз; `top` и низ ряда растут вместе с номером.
   */
  rows: StickerRow<T>[];

  /**
   * Верхи разделов в порядке ленты.
   */
  sectionTops: SectionTop[];

  /**
   * Высота всей ленты в пикселях — высота контейнера прокрутки.
   */
  total: number;
};

/**
 * Полуоткрытый диапазон номеров рядов `[from, to)`: `from` — первый ряд окна, `to` — ряд сразу за последним.
 */
export type RowRange = [from: number, to: number];
