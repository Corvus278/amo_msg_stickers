export type TelegramImportState = {
  /**
   * Ссылка на пак или его имя, как ввёл пользователь.
   */
  link: string;

  /**
   * Меняет введённую ссылку.
   */
  changeLink: (link: string) => void;

  /**
   * Идёт импорт: повторный запуск недоступен.
   */
  isImporting: boolean;

  /**
   * Доля обработанных стикеров в процентах; `null` — импорт не идёт, полоса прогресса
   * скрыта: после успеха и после ошибки её нет.
   */
  percent: number | null;

  /**
   * Импортирует пак по ссылке. Промис не отклоняется: ошибка уходит в статус, по
   * успеху открывается вкладка пака.
   */
  startImport: () => Promise<void>;
};
