/**
 * Место вкладки в полосе.
 */
export type TabBox = {
  /**
   * Левый край вкладки от начала содержимого полосы, в пикселях.
   */
  left: number;

  /**
   * Ширина вкладки в пикселях.
   */
  width: number;
};

/**
 * Видимая часть полосы вкладок.
 */
export type StripBox = {
  /**
   * Текущая прокрутка полосы вбок, в пикселях.
   */
  scrollLeft: number;

  /**
   * Видимая ширина полосы в пикселях.
   */
  width: number;

  /**
   * Внутренний отступ полосы у левого и правого края, в пикселях: крайняя вкладка встаёт к
   * краю вместе с ним, а не прижимается к краю вплотную.
   */
  inset: number;
};
