/**
 * Битмап, который держит декодированный кадр до `close`.
 */
export type Closable = {
  /**
   * Освобождает память кадра.
   */
  close: () => void;
};

/**
 * Кэш битмапов обложек по id стикера на одно открытие попапа.
 */
export type CoverBitmaps<B extends Closable> = {
  /**
   * Битмап стикера: первый запрос id декодирует его `load`, следующие отдают тот же.
   * `null` — декодирование не удалось или кэш закрыли, пока оно шло.
   */
  get: (id: string, load: () => Promise<B>) => Promise<B | null>;

  /**
   * Закрывает все битмапы кэша, в том числе те, что ещё декодируются.
   */
  close: () => void;
};

/**
 * Размер кадра в пикселях.
 */
export type CoverSize = {
  /**
   * Ширина кадра.
   */
  width: number;

  /**
   * Высота кадра.
   */
  height: number;
};
