/**
 * Место плитки в раскладке ленты.
 */
export type TilePlace = {
  /**
   * Номер колонки слева.
   */
  column: number;

  /**
   * Верх плитки от начала ленты, в пикселях.
   */
  top: number;

  /**
   * Высота плитки в пикселях.
   */
  height: number;
};

/**
 * Прямоугольник плитки для абсолютного позиционирования в ленте.
 */
export type TileRect = {
  /**
   * Отступ от левого края ленты, в пикселях.
   */
  left: number;

  /**
   * Отступ от верха ленты, в пикселях.
   */
  top: number;

  /**
   * Ширина плитки — ширина колонки.
   */
  width: number;

  /**
   * Высота плитки в пикселях.
   */
  height: number;
};
