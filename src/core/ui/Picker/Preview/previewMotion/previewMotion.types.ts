/**
 * Прямоугольник на экране: подмножество `DOMRect`, которое нужно полёту. Чистая функция не
 * зависит от DOM.
 */
export type RectLike = {
  /**
   * Левая граница, px от левого края окна.
   */
  left: number;

  /**
   * Верхняя граница, px от верхнего края окна.
   */
  top: number;

  /**
   * Ширина, px.
   */
  width: number;

  /**
   * Высота, px.
   */
  height: number;
};

/**
 * Идущий уход предпросмотра.
 */
export type PreviewLeave = {
  /**
   * Завершается, когда доиграли все анимации ухода или их отменили. Не отклоняется.
   */
  finished: Promise<void>;

  /**
   * Прерывает уход: узлы возвращаются в обычное состояние.
   */
  cancel: () => void;
};

/**
 * Узлы, которые анимирует открытие и закрытие предпросмотра.
 */
export type PreviewOpenTargets = {
  /**
   * Кнопка ячейки, с которой открыт предпросмотр: из неё вылетает картинка.
   */
  source: HTMLElement;

  /**
   * Квадрат картинки предпросмотра: летит из ячейки на своё место.
   */
  flight: HTMLElement;

  /**
   * Эмодзи над картинкой; `null` — у стикера его нет.
   */
  emoji: HTMLElement | null;
};
