/**
 * Анимация появления экрана — в той мере, в какой её касается уход.
 */
export type ScreenLeaveMotion = {
  /**
   * Скорость проигрывания; знак обращает `reverse()`.
   */
  playbackRate: number;

  /**
   * Проигрывание в обратную сторону с текущего места.
   */
  reverse: () => void;

  /**
   * Конец проигрывания; отклоняется при отмене анимации.
   */
  finished: Promise<unknown>;
};

export type PlayScreenLeaveOptions = {
  /**
   * Анимация появления экрана. null — анимации нет, экран закрывается сразу.
   */
  motion: ScreenLeaveMotion | null;

  /**
   * В системе включено уменьшение движения: экран закрывается сразу.
   */
  isReduced: boolean;

  /**
   * Смонтирован ли экран сейчас. Экран, снятый во время ухода другим путём, конец анимации
   * не закрывает.
   */
  isMounted: () => boolean;

  /**
   * Колбэк на закрытие экрана.
   */
  onClose: () => void;
};
