/**
 * Прямоугольник в координатах окна, в пикселях. Точка — прямоугольник нулевого размера.
 */
export type Box = {
  /**
   * Левый край.
   */
  left: number;

  /**
   * Верхний край.
   */
  top: number;

  /**
   * Правый край.
   */
  right: number;

  /**
   * Нижний край.
   */
  bottom: number;
};

/**
 * Размер меню в пикселях.
 */
export type MenuSize = {
  /**
   * Ширина меню.
   */
  width: number;

  /**
   * Высота меню.
   */
  height: number;
};

/**
 * Точка в координатах окна, в пикселях: левый верхний угол меню или место правого клика, от
 * которого меню открывается.
 */
export type MenuPoint = {
  /**
   * Расстояние от левого края окна: левый край меню или место клика.
   */
  left: number;

  /**
   * Расстояние от верхнего края окна: верхний край меню или место клика.
   */
  top: number;
};
