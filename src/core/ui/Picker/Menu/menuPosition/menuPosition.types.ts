/**
 * Прямоугольник в координатах окна, в пикселях. Точка — прямоугольник нулевого размера.
 */
export type Box = {
  /**
   * Левый край.
   */
  left: number;

  /**
   * Верхний край.
   */
  top: number;

  /**
   * Правый край.
   */
  right: number;

  /**
   * Нижний край.
   */
  bottom: number;
};

/**
 * Размер меню в пикселях.
 */
export type MenuSize = {
  /**
   * Ширина меню.
   */
  width: number;

  /**
   * Высота меню.
   */
  height: number;
};

/**
 * Левый верхний угол меню в координатах окна, в пикселях.
 */
export type MenuPoint = {
  /**
   * Левый край меню.
   */
  left: number;

  /**
   * Верхний край меню.
   */
  top: number;
};
