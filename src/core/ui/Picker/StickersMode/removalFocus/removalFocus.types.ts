/**
 * Куда перевести фокус после удаления: ячейка раздела или вкладка раздела в полосе.
 */
export type FocusTarget =
  | {
      /**
       * Ячейка ленты.
       */
      kind: 'cell';

      /**
       * Раздел ячейки.
       */
      sectionId: string;

      /**
       * Ключ ячейки в разделе.
       */
      key: string;
    }
  | {
      /**
       * Вкладка раздела: полоса вкладок не виртуализирована, и вкладка есть в документе всегда.
       */
      kind: 'tab';

      /**
       * Раздел вкладки.
       */
      sectionId: string;
    };

/**
 * Раздел ленты в той мере, в какой он нужен выбору фокуса.
 */
export type FocusSection = {
  /**
   * Идентификатор раздела.
   */
  id: string;

  /**
   * Ячейки раздела в порядке показа.
   */
  items: ReadonlyArray<{
    /**
     * Ключ ячейки, уникальный в разделе.
     */
    key: string;
  }>;
};
