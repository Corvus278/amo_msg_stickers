import type { LocalSendItem, Pack, StickerRec } from '../../../../db.types';

/**
 * Стикер в ленте: одна ячейка сетки раздела.
 */
export type FeedSticker = {
  /**
   * Ключ ячейки, уникальный в разделе: id стикера у паков, ключ записи у недавних.
   */
  key: string;

  /**
   * Что отправляет ячейка.
   */
  item: LocalSendItem;

  /**
   * Запись стикера: блоб для картинки ячейки. Object URL создаётся только при показе ячейки.
   */
  sticker: StickerRec;

  /**
   * Имя стикера в винительном падеже для кнопок ячейки.
   */
  name: string;
};

/**
 * Раздел ленты стикеров.
 */
export type FeedSection = {
  /**
   * Идентификатор раздела: `pack.id` у паков, `recent` у недавних.
   */
  id: string;

  /**
   * Название раздела в заголовке и подсказке вкладки.
   */
  title: string;

  /**
   * Пак раздела — для обложки вкладки; `null` у недавних. Тот же объект, что в списке паков
   * пикера: вкладка перечитывает обложку при его смене.
   */
  pack: Pack | null;

  /**
   * Стикеры раздела в порядке показа.
   */
  items: FeedSticker[];

  /**
   * Подсказка вместо сетки, когда стикеров нет.
   */
  hint: string;
};
