export type SectionScrollPlanOptions = {
  /**
   * Текущая прокрутка ленты, в пикселях.
   */
  from: number;

  /**
   * Прокрутка, при которой заголовок раздела встаёт вверх ленты, в пикселях. Может лежать за
   * пределами прокрутки: заголовок короткого последнего раздела до верха не доезжает.
   */
  to: number;

  /**
   * Высота видимой области ленты, в пикселях.
   */
  viewport: number;

  /**
   * Наибольшая прокрутка ленты — высота содержимого минус видимая область, в пикселях.
   * Отрицательная, если лента короче видимой области.
   */
  maxScroll: number;
};

export type SectionScrollPlan = {
  /**
   * Прокрутка, которую ставят мгновенно перед плавным доездом; `null` — цель ближе одной видимой
   * области, и лента едет к ней плавно от текущего места.
   */
  jumpTo: number | null;

  /**
   * Прокрутка, к которой лента доезжает плавно, — уже в пределах `[0, maxScroll]`.
   */
  target: number;
};
