/**
 * Приёмник кадров одного прохода: конвейеру всё равно, где идёт кодирование.
 */
export type FrameSink = {
  /**
   * Отдаёт кадр в кодирование. После вызова буфер `rgba` вызывающему не принадлежит: его
   * могут передать в другой поток. Промис разрешается, когда можно слать следующий кадр.
   */
  write: (rgba: Uint8ClampedArray, delayMs: number) => Promise<void>;

  /**
   * Разрешается, когда все отданные `write`-ом кадры закодированы. Без него `byteLength`
   * может не учитывать кадры, ещё стоящие в очереди кодирования.
   */
  flush: () => Promise<void>;

  /**
   * Вес GIF в байтах по уже закодированным кадрам. Полный вес всех отданных кадров он даёт
   * только после `await flush()`: до него отстаёт на кадры в очереди кодирования.
   */
  readonly byteLength: number;

  /**
   * Закрывает GIF и отдаёт его байты; дальше писать кадры нельзя.
   */
  finish: () => Promise<Uint8Array<ArrayBuffer>>;

  /**
   * Освобождает приёмник. Зовётся один раз при любом исходе прохода, в том числе без `finish`.
   */
  close: () => void;
};
