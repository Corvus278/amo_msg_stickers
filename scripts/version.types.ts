export type Version = {
  /**
   * Несовместимые изменения: схема IndexedDB, переделка продукта.
   */
  major: number;
  /**
   * Новое поведение, видимое пользователю: функция, источник, настройка.
   */
  minor: number;
  /**
   * Изменения продукта без нового поведения: исправления, рефактор, производительность,
   * зависимости.
   */
  patch: number;
};

export type VersionSource = {
  /**
   * Где записана версия — попадает в текст ошибки.
   */
  source: string;
  /**
   * Версия; `undefined` — в источнике её не нашли.
   */
  version: string | undefined;
};
